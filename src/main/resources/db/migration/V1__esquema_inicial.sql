-- ---------- Catalogos ----------

CREATE TABLE categorias (
    categoria_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre_categoria)
);

CREATE TABLE estados (
    estado_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_estado VARCHAR(50) NOT NULL,
    CONSTRAINT uk_estados_nombre UNIQUE (nombre_estado)
);

CREATE TABLE sexos (
    sexo_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_sexo VARCHAR(50) NOT NULL,
    CONSTRAINT uk_sexos_nombre UNIQUE (nombre_sexo)
);

CREATE TABLE roles (
    rol_id          UUID PRIMARY KEY,
    nombre_rol      VARCHAR(50) NOT NULL,
    descripcion_rol VARCHAR(200),
    CONSTRAINT uk_roles_nombre UNIQUE (nombre_rol)
);

CREATE TABLE tipo_pagos (
    tipo_pago_id     UUID PRIMARY KEY,
    nombre_tipo_pago VARCHAR(50) NOT NULL,
    CONSTRAINT uk_tipo_pagos_nombre UNIQUE (nombre_tipo_pago)
);

CREATE TABLE ubicacion (
    id               UUID PRIMARY KEY,
    nombre_ubicacion VARCHAR(255) NOT NULL,
    CONSTRAINT uk_ubicacion_nombre UNIQUE (nombre_ubicacion)
);

CREATE TABLE instituciones (
    institucion_id           UUID PRIMARY KEY,
    nombre_institucion       VARCHAR(100) NOT NULL,
    departamento_institucion VARCHAR(100) NOT NULL,
    municipio_institucion    VARCHAR(100)
);

CREATE TABLE valoraciones_categorias (
    valoracion_categoria_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_valoracion_categoria VARCHAR(100) NOT NULL,
    CONSTRAINT uk_valoraciones_categorias_nombre UNIQUE (nombre_valoracion_categoria)
);

-- ---------- Usuarios ----------

CREATE TABLE usuarios (
    documento_usuario           INTEGER PRIMARY KEY,
    nombre_usuario              VARCHAR(100)     NOT NULL,
    primer_apellido_usuario     VARCHAR(50)      NOT NULL,
    segundo_apellido_usuario    VARCHAR(50),
    correo_usuario              VARCHAR(100)     NOT NULL,
    clave_usuario               VARCHAR(255)     NOT NULL,
    telefono_usuario            VARCHAR(20)      NOT NULL,
    bloqueado                   BOOLEAN          NOT NULL DEFAULT FALSE,
    fecha_nacimiento_usuario    TIMESTAMP(6)     NOT NULL,
    valoracion_conteo_usuario   INTEGER          NOT NULL DEFAULT 0,
    valoracion_promedio_usuario DOUBLE PRECISION NOT NULL DEFAULT 0,
    sexo_id                     BIGINT           NOT NULL,
    rol_id                      UUID             NOT NULL,
    CONSTRAINT uk_usuarios_correo UNIQUE (correo_usuario),
    CONSTRAINT uk_usuarios_telefono UNIQUE (telefono_usuario),
    CONSTRAINT fk_usuario_sexo FOREIGN KEY (sexo_id) REFERENCES sexos (sexo_id),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES roles (rol_id)
);

CREATE INDEX idx_usuarios_sexo ON usuarios (sexo_id);
CREATE INDEX idx_usuarios_rol ON usuarios (rol_id);

-- ---------- Trabajos ----------

CREATE TABLE trabajos (
    trabajo_id                UUID PRIMARY KEY,
    titulo_trabajo            VARCHAR(150)     NOT NULL,
    descripcion_trabajo       VARCHAR(500)     NOT NULL,
    fecha_publicacion_trabajo TIMESTAMP(6)     NOT NULL,
    pago_trabajo              DOUBLE PRECISION NOT NULL DEFAULT 0,
    ubicacion_id              UUID             NOT NULL,
    solicitante_id            INTEGER          NOT NULL,
    trabajador_id             INTEGER,
    estados_id                BIGINT           NOT NULL,
    categorias_id             BIGINT           NOT NULL,
    tipos_de_pago_id          UUID,
    CONSTRAINT fk_trabajo_ubicacion FOREIGN KEY (ubicacion_id) REFERENCES ubicacion (id),
    CONSTRAINT fk_trabajo_solicitante FOREIGN KEY (solicitante_id) REFERENCES usuarios (documento_usuario),
    CONSTRAINT fk_trabajo_trabajador FOREIGN KEY (trabajador_id) REFERENCES usuarios (documento_usuario),
    CONSTRAINT fk_trabajo_estados FOREIGN KEY (estados_id) REFERENCES estados (estado_id),
    CONSTRAINT fk_trabajo_categorias FOREIGN KEY (categorias_id) REFERENCES categorias (categoria_id),
    CONSTRAINT fk_trabajo_tipo_pago FOREIGN KEY (tipos_de_pago_id) REFERENCES tipo_pagos (tipo_pago_id)
);

CREATE INDEX idx_trabajos_ubicacion ON trabajos (ubicacion_id);
CREATE INDEX idx_trabajos_solicitante ON trabajos (solicitante_id);
CREATE INDEX idx_trabajos_trabajador ON trabajos (trabajador_id);
CREATE INDEX idx_trabajos_estado ON trabajos (estados_id);
CREATE INDEX idx_trabajos_categoria ON trabajos (categorias_id);
CREATE INDEX idx_trabajos_tipo_pago ON trabajos (tipos_de_pago_id);

-- ---------- Solicitudes (postulaciones) ----------

CREATE TABLE solicitudes (
    solicitud_id       UUID PRIMARY KEY,
    usuario_id         INTEGER      NOT NULL,
    trabajo_id         UUID         NOT NULL,
    estado             VARCHAR(255),
    fecha_solicitud    TIMESTAMP(6),
    fecha_modificacion TIMESTAMP(6),
    CONSTRAINT ck_solicitudes_estado CHECK (estado IN ('PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'CERRADA')),
    CONSTRAINT fk_usuario_solicitud FOREIGN KEY (usuario_id) REFERENCES usuarios (documento_usuario),
    CONSTRAINT fk_trabajo_solicitud FOREIGN KEY (trabajo_id) REFERENCES trabajos (trabajo_id)
);

CREATE INDEX idx_solicitudes_usuario ON solicitudes (usuario_id);
CREATE INDEX idx_solicitudes_trabajo ON solicitudes (trabajo_id);

-- ---------- Valoraciones ----------

CREATE TABLE valoraciones (
    valoracion_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajo_id            UUID         NOT NULL,
    categoria_id          BIGINT       NOT NULL,
    puntuacion_valoracion INTEGER      NOT NULL DEFAULT 0,
    comentario_valoracion VARCHAR(500),
    CONSTRAINT fk_valoracion_trabajo FOREIGN KEY (trabajo_id) REFERENCES trabajos (trabajo_id),
    CONSTRAINT fk_valoracion_categoria FOREIGN KEY (categoria_id) REFERENCES valoraciones_categorias (valoracion_categoria_id)
);

CREATE INDEX idx_valoraciones_trabajo ON valoraciones (trabajo_id);
CREATE INDEX idx_valoraciones_categoria ON valoraciones (categoria_id);
